                2 => @call(.always_inline, impl.mulhsu, .{ vm, inst }),
                3 => @call(.always_inline, impl.mulhu, .{ vm, inst }),
                4 => @call(.always_inline, impl.div, .{ vm, inst }),
                5 => @call(.always_inline, impl.divu, .{ vm, inst }),
