                5 => switch (@as(u3, @truncate(inst.raw >> 12))) {
                    0 => @call(.always_inline, impl.@"fmin.s", .{ vm, inst }),
                    1 => @call(.always_inline, impl.@"fmax.s", .{ vm, inst }),
                    else => error.InvalidInstruction,
                },
                8 => @call(.always_inline, impl.@"fcvt.s.d", .{ vm, inst }),
                11 => @call(.always_inline, impl.@"fsqrt.s", .{ vm, inst }),
                20 => switch (@as(u3, @truncate(inst.raw >> 12))) {
                    0 => @call(.always_inline, impl.@"fle.s", .{ vm, inst }),
                    1 => @call(.always_inline, impl.@"flt.s", .{ vm, inst }),
                    2 => @call(.always_inline, impl.@"feq.s", .{ vm, inst }),
                    else => error.InvalidInstruction,
                },
                24 => switch (@as(u5, @truncate(inst.raw >> 20))) {
                    0 => @call(.always_inline, impl.@"fcvt.w.s", .{ vm, inst }),
                    1 => @call(.always_inline, impl.@"fcvt.wu.s", .{ vm, inst }),
                    2 => @call(.always_inline, impl.@"fcvt.l.s", .{ vm, inst }),
                    3 => @call(.always_inline, impl.@"fcvt.lu.s", .{ vm, inst }),
                    else => error.InvalidInstruction,
                },
                26 => switch (@as(u5, @truncate(inst.raw >> 20))) {
                    0 => @call(.always_inline, impl.@"fcvt.s.w", .{ vm, inst }),
                    1 => @call(.always_inline, impl.@"fcvt.s.wu", .{ vm, inst }),
                    2 => @call(.always_inline, impl.@"fcvt.s.l", .{ vm, inst }),
                    3 => @call(.always_inline, impl.@"fcvt.s.lu", .{ vm, inst }),
